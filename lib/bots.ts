// Shorthand builder — fills in null-safe defaults so each item declaration is concise
function item(
  id: string,
  title: string,
  sub_type: string,
  brand: string,
  material: string,
  color_primary: string,
  color_secondary: string | null,
  pattern: string,
  formality: string,
  aesthetic_tags: string[],
  pros: string[],
  cons: string[],
  color_pairings: string[],
  color_clashes: string[]
): GarmentForScoring {
  return {
    id,
    title,
    brand,
    sub_type,
    material,
    color_primary,
    color_secondary,
    pattern,
    formality,
    aesthetic_tags,
    pros,
    cons,
    color_pairings,
    color_clashes,
    tags: null,
    image: null,
  };
}

